CREATE TABLE SHIPMENT
  ( TRACKING_NUMBER    CHAR(14)      NOT NULL
  , CARRIER_CODE       CHAR(3)       NOT NULL
  , RECIPIENT_NAME     CHAR(30)      NOT NULL
  , RECIPIENT_CITY     CHAR(20)      NOT NULL
  , SHIPMENT_STATUS    CHAR(2)       NOT NULL
  , SHIPPED_ON         DATE          NOT NULL
  , PROMISED_ON        DATE          NOT NULL
  , DELIVERED_AT       TIMESTAMP              -- NULL until delivered
  , DELIVERY_ATTEMPTS  SMALLINT      NOT NULL DEFAULT 0
  , DECLARED_VALUE     DECIMAL(9,2)  NOT NULL
  , PRIMARY KEY (TRACKING_NUMBER)
  );

CREATE INDEX SHIPMENT_BY_CARRIER ON SHIPMENT (CARRIER_CODE, SHIPMENT_STATUS);

CREATE TABLE SHIPMENT_EVENT
  ( TRACKING_NUMBER    CHAR(14)      NOT NULL
  , OCCURRED_AT        TIMESTAMP     NOT NULL
  , EVENT_STATUS       CHAR(2)       NOT NULL
  , LOCATION           CHAR(20)      NOT NULL
  , PRIMARY KEY (TRACKING_NUMBER, OCCURRED_AT)
  );

